package domain

import (
	"fmt"
	"regexp"
	"sort"
	"strings"
	"time"
)

// The OpenBao host-identity vocabulary. Every name, path, and lifetime is
// derived here, so the adapter can send it without deciding any of it, and two
// hosts can never land on the same role, policy, or KV prefix.
const (
	// HostKVPathPrefix is the KV v2 data prefix every per-host secret lives under.
	// The next path segment is the host's own identity.
	HostKVPathPrefix = "secret/data/hosts/"
	// HostMetadataPathPrefix is the KV v2 metadata prefix for the same tree.
	HostMetadataPathPrefix = "secret/metadata/hosts/"
	// RoleClaimPathPrefix is the non-secret ownership record for one AppRole. It
	// is what a second host collides with, and it holds no credential.
	RoleClaimPathPrefix = "secret/data/fleet/identity/roles/"
	// HostRolePrefix and HostPolicyPrefix are prepended to the host identity, so
	// the role and the policy of a host carry its identity in their names.
	HostRolePrefix   = "fleet-host-"
	HostPolicyPrefix = "fleet-policy-"
	// AppRolePathPrefix is the AppRole mount path.
	AppRolePathPrefix = "auth/approle/role/"
	// SecretIDPathSuffix is appended to a role path to mint or rotate a SecretID.
	SecretIDPathSuffix = "/secret-id"
	// AppRoleLoginPath is the login endpoint.
	AppRoleLoginPath = "auth/approle/login"
	// WrappingUnwrapPath unwraps a response-wrapped token. It is the only endpoint
	// that consumes a wrapping token, and OpenBao consumes it exactly once.
	WrappingUnwrapPath = "sys/wrapping/unwrap"
	// TokenRenewPath renews the token already in hand.
	TokenRenewPath = "auth/token/renew-self"
	// TokenAccessorsPath lists every issued token accessor (LIST, with `?list=true`
	// appended by the adapter). It is the only way to find an already-issued token:
	// neither an AppRole nor a policy holds a reference to the tokens it produced.
	TokenAccessorsPath = "auth/token/accessors"
	// TokenLookupAccessorPath reports the policies one accessor carries, so a
	// teardown can attribute a token to this host without ever reading its value.
	TokenLookupAccessorPath = "auth/token/lookup-accessor"
	// TokenRevokeAccessorPath invalidates one issued token by accessor. This is the
	// call that actually cuts off a session handed out before the teardown began.
	TokenRevokeAccessorPath = "auth/token/revoke-accessor"
)

// Token lifetimes. The hard maximum is the step's own bound: a host token is
// never valid for longer than 900 seconds, so a leaked token expires while an
// operator can still see the job that minted it.
const (
	// AuthorizationTokenTTL is the requested lifetime of a host token.
	AuthorizationTokenTTL = 10 * time.Minute
	// MaxAuthorizationTokenTTL is the hard maximum any host token may claim.
	MaxAuthorizationTokenTTL = 15 * time.Minute
	// TokenRenewIncrement is the lease extension a renewal asks for. It is capped
	// by MaxAuthorizationTokenTTL, so renewal can never extend past the bound.
	TokenRenewIncrement = 5 * time.Minute
	// BootstrapWrapTTL is how long the one-use wrapping token is valid. It is one
	// delivery window, not a credential lifetime: the host unwraps it once.
	BootstrapWrapTTL = 10 * time.Minute
)

// Reboot-safe login credential. The bootstrap SecretID is deliberately one-use,
// so it cannot be the credential a host logs in with after a reboot. A separate
// rotating SecretID carries a real lifetime and more than one use; the host
// consumes at most one use per boot, and it is replaced before it runs out.
const (
	// LoginSecretIDTTL is the lifetime of a rotating login SecretID.
	LoginSecretIDTTL = 12 * time.Hour
	// LoginSecretIDUses is how many logins one rotating SecretID allows. Two would
	// be the minimum for a single reboot; eight tolerates a short reboot loop
	// before rotation has to catch up.
	LoginSecretIDUses = 8
	// LoginSecretRotationInterval is how often the rotating SecretID is replaced.
	// It is shorter than LoginSecretIDTTL, so rotation always happens before
	// expiry.
	LoginSecretRotationInterval = 6 * time.Hour
	// LoginSecretRotationGrace keeps the previous SecretID usable for a short
	// overlap so a host booting during a rotation still logs in.
	LoginSecretRotationGrace = 30 * time.Minute
)

// hostIDPattern bounds a host identity. Identities are generated by the service
// (`host-0001`), never accepted from a client, and the pattern is what keeps one
// out of a role name, a policy name, or a KV path as anything but a single safe
// segment.
var hostIDPattern = regexp.MustCompile(`^[a-z][a-z0-9-]{2,63}$`)

// ValidateHostID enforces the host-identity shape.
func ValidateHostID(hostID string) error {
	if !hostIDPattern.MatchString(hostID) {
		return Invalid("host_id", "must be 3 to 64 characters of [a-z0-9-] starting with a letter")
	}
	return nil
}

// HostRoleName derives the AppRole name from the host identity. It is a pure
// function of the identity: no two distinct host identities produce the same
// name, and no host name, profile, or client input participates.
func HostRoleName(hostID string) (string, error) {
	if err := ValidateHostID(hostID); err != nil {
		return "", err
	}
	return HostRolePrefix + hostID, nil
}

// HostPolicyName derives the ACL policy name from the host identity, by the same
// rule as the role.
func HostPolicyName(hostID string) (string, error) {
	if err := ValidateHostID(hostID); err != nil {
		return "", err
	}
	return HostPolicyPrefix + hostID, nil
}

// HostIdentity is the complete, derived identity of one host: its role, its
// policy, and the KV tree it owns. It carries no credential and no client input.
type HostIdentity struct {
	HostID     string
	HostName   string
	RoleName   string
	PolicyName string
	// KVPath is the host's own data prefix, `secret/data/hosts/<host>`.
	KVPath string
}

// NewHostIdentity derives the identity for one host. The host name is validated
// with the same rule the API applies, so a name that reached this point is known
// to be a single safe label.
func NewHostIdentity(hostID, hostName string) (HostIdentity, error) {
	if err := ValidateHostID(hostID); err != nil {
		return HostIdentity{}, err
	}
	if err := ValidateHostName(hostName); err != nil {
		return HostIdentity{}, err
	}
	roleName, err := HostRoleName(hostID)
	if err != nil {
		return HostIdentity{}, err
	}
	policyName, err := HostPolicyName(hostID)
	if err != nil {
		return HostIdentity{}, err
	}
	return HostIdentity{
		HostID:     hostID,
		HostName:   hostName,
		RoleName:   roleName,
		PolicyName: policyName,
		KVPath:     HostKVPathPrefix + hostID,
	}, nil
}

// MetadataPath is the host's metadata prefix, which a reader needs for listing.
func (h HostIdentity) MetadataPath() string {
	return HostMetadataPathPrefix + h.HostID
}

// CanaryPath is the approved non-sensitive sentinel secret of this host. It is
// the path the live acceptance check reads.
func (h HostIdentity) CanaryPath() string {
	return h.KVPath + "/canary"
}

// CanaryRef is CanaryPath as a `bao:` reference, which is the form a bundle and a
// policy document use.
func (h HostIdentity) CanaryRef() string {
	return "bao:" + h.CanaryPath()
}

// RoleClaimPath is the non-secret record that binds this host's role name to the
// host. It is created once and read before a role is created, so a role can
// never move to another host.
func (h HostIdentity) RoleClaimPath() (string, error) {
	return RoleClaimPath(h.RoleName)
}

// RoleClaimPath returns the ownership record path for a role name.
func RoleClaimPath(roleName string) (string, error) {
	if !roleNamePattern.MatchString(roleName) {
		return "", Invalid("role_name", "must be a derived fleet role name")
	}
	return RoleClaimPathPrefix + roleName, nil
}

// roleNamePattern is the shape of every name this package derives: the fleet
// prefix plus a validated host identity.
var roleNamePattern = regexp.MustCompile(`^fleet-host-[a-z][a-z0-9-]{2,63}$`)

// OwnsPath reports whether a `bao:` reference names this host's own KV tree.
// Anything else — another host's tree, a shared path, a different scheme — is
// not the host's to read.
func (h HostIdentity) OwnsPath(ref string) bool {
	scheme, path, found := strings.Cut(ref, ":")
	if !found || scheme != "bao" {
		return false
	}
	return path == h.KVPath || strings.HasPrefix(path, h.KVPath+"/")
}

// ValidateHostBundle refuses a bundle reference the host does not own. The
// profile renders the per-host path, and this is the second check: a bundle that
// escaped its host prefix would grant another host's secret, so it fails here
// even if a future profile template were wrong.
func (h HostIdentity) ValidateHostBundle(ref string) error {
	if err := ValidateSecretRef(ref); err != nil {
		return fmt.Errorf("host %s: %w", h.HostID, err)
	}
	if !h.OwnsPath(ref) {
		return Invalid("secret_bundles", fmt.Sprintf("%q is outside host %s's own KV path %s", ref, h.HostID, h.KVPath))
	}
	return nil
}

// PolicyCapability is one ACL capability in a rendered policy document.
type PolicyCapability string

// The capabilities a host policy uses. `deny` overrides every grant, which is
// what makes the identity-mutation denials hold even if a broader grant is added
// later.
const (
	CapabilityRead  PolicyCapability = "read"
	CapabilityList  PolicyCapability = "list"
	CapabilityDeny  PolicyCapability = "deny"
	CapabilityAllow PolicyCapability = "*"
)

// PolicyRule is one path and its capabilities.
type PolicyRule struct {
	Path         string
	Capabilities []PolicyCapability
}

// PolicyDocument is the complete, structured ACL policy for one host. The
// adapter renders it with HCL and sends exactly that text; the tests assert the
// structured rules and the rendered text agree.
type PolicyDocument struct {
	Name   string
	HostID string
	Rules  []PolicyRule
}

// identityMutationPaths are the endpoints a host must never call: creating or
// changing an AppRole, minting or rotating a SecretID, creating a token, editing
// a policy, touching an entity, or mounting an auth method. An explicit deny is
// what makes the restriction independent of any future allow.
var identityMutationPaths = []string{
	AppRolePathPrefix + "*",
	AppRolePathPrefix + "+" + SecretIDPathSuffix,
	"auth/token/create*",
	"auth/token/revoke*",
	"auth/token/roles/*",
	"sys/policies/acl*",
	"sys/auth*",
	"identity/*",
}

// HostPolicyDocument builds the policy a host logs in with. It allows reading
// exactly the host's own KV tree (the canary and anything else under
// `secret/data/hosts/<host>/`) plus the metadata listing of that tree, and it
// denies every identity-mutation endpoint. Another host's path is not granted at
// all, and an explicit deny overrides the grants if one is ever added.
func HostPolicyDocument(identity HostIdentity, bundles []string) (PolicyDocument, error) {
	if identity.HostID == "" {
		return PolicyDocument{}, Invalid("host_id", "is required")
	}
	for _, ref := range bundles {
		if err := identity.ValidateHostBundle(ref); err != nil {
			return PolicyDocument{}, err
		}
	}
	rules := []PolicyRule{
		{
			Path:         identity.KVPath + "/*",
			Capabilities: []PolicyCapability{CapabilityRead},
		},
		{
			Path:         identity.MetadataPath() + "/*",
			Capabilities: []PolicyCapability{CapabilityRead, CapabilityList},
		},
	}
	for _, path := range identityMutationPaths {
		rules = append(rules, PolicyRule{Path: path, Capabilities: []PolicyCapability{CapabilityDeny}})
	}
	return PolicyDocument{Name: identity.PolicyName, HostID: identity.HostID, Rules: rules}, nil
}

// HCL renders the policy in the ACL policy language OpenBao accepts. The output
// is deterministic: the rules are emitted in the order the document builds them.
func (p PolicyDocument) HCL() string {
	var out strings.Builder
	fmt.Fprintf(&out, "# Fleet host policy for %s. Generated by the fleet provisioning service.\n", p.HostID)
	for _, rule := range p.Rules {
		capabilities := make([]string, 0, len(rule.Capabilities))
		for _, capability := range rule.Capabilities {
			capabilities = append(capabilities, string(capability))
		}
		fmt.Fprintf(&out, "path %q {\n  capabilities = [%s]\n}\n", rule.Path, quoteList(capabilities))
	}
	return out.String()
}

func quoteList(values []string) string {
	quoted := make([]string, 0, len(values))
	for _, value := range values {
		quoted = append(quoted, fmt.Sprintf("%q", value))
	}
	return strings.Join(quoted, ", ")
}

// AllowsRead reports whether the policy grants a read of path. A deny on any
// matching rule wins, which is the semantics OpenBao applies. It is used by tests
// and by the use case to prove a policy is scoped to one host before it is sent.
func (p PolicyDocument) AllowsRead(path string) bool {
	allowed := false
	for _, rule := range p.Rules {
		if !policyPathMatches(rule.Path, path) {
			continue
		}
		for _, capability := range rule.Capabilities {
			switch capability {
			case CapabilityDeny:
				return false
			case CapabilityRead, CapabilityAllow:
				allowed = true
			}
		}
	}
	return allowed
}

// Denies reports whether an explicit deny rule matches path. Deny overrides every
// grant in OpenBao, so this is the question a test asks about the policy's write
// scoping.
func (p PolicyDocument) Denies(path string) bool {
	for _, rule := range p.Rules {
		if !policyPathMatches(rule.Path, path) {
			continue
		}
		for _, capability := range rule.Capabilities {
			if capability == CapabilityDeny {
				return true
			}
		}
	}
	return false
}

// policyPathMatches implements the subset of OpenBao path matching this package
// emits: an exact path or one trailing `*` wildcard. A `+` segment matches
// exactly one path segment, which is enough for the deny rules.
func policyPathMatches(pattern, path string) bool {
	if strings.HasSuffix(pattern, "*") {
		return strings.HasPrefix(path, strings.TrimSuffix(pattern, "*"))
	}
	patternParts := strings.Split(pattern, "/")
	pathParts := strings.Split(path, "/")
	if len(patternParts) != len(pathParts) {
		return false
	}
	for i := range patternParts {
		if patternParts[i] != "+" && patternParts[i] != pathParts[i] {
			return false
		}
	}
	return true
}

// TokenPolicy is the short-lived, renewable token policy a host role carries.
type TokenPolicy struct {
	TTL            time.Duration
	MaxTTL         time.Duration
	RenewIncrement time.Duration
	Renewable      bool
}

// DefaultTokenPolicy is the policy the adapter configures on every role.
func DefaultTokenPolicy() TokenPolicy {
	return TokenPolicy{
		TTL:            AuthorizationTokenTTL,
		MaxTTL:         MaxAuthorizationTokenTTL,
		RenewIncrement: TokenRenewIncrement,
		Renewable:      true,
	}
}

// Validate enforces that a token is short-lived and renewable: a lifetime above
// zero, a hard maximum at or below 900 seconds, and a max TTL that is not below
// the TTL.
func (p TokenPolicy) Validate() error {
	if !p.Renewable {
		return Invalid("token_policy", "a host token must be renewable so a working job can finish")
	}
	if p.TTL <= 0 {
		return Invalid("token_ttl", "must be greater than zero")
	}
	if p.MaxTTL <= 0 {
		return Invalid("token_max_ttl", "must be greater than zero")
	}
	if p.MaxTTL > MaxAuthorizationTokenTTL {
		return Invalid("token_max_ttl", fmt.Sprintf("%s exceeds the hard maximum of %s", p.MaxTTL, MaxAuthorizationTokenTTL))
	}
	if p.TTL > p.MaxTTL {
		return Invalid("token_ttl", "must not exceed token_max_ttl")
	}
	if p.RenewIncrement <= 0 || p.RenewIncrement > p.MaxTTL {
		return Invalid("token_renew_increment", "must be greater than zero and no greater than the maximum TTL")
	}
	return nil
}

// LoginCredentialPolicy is the reboot-safe rotating SecretID policy. It is
// separate from the one-use bootstrap SecretID on purpose: the bootstrap
// credential is consumed by the first unwrap, and this one is what a host uses on
// every subsequent boot.
type LoginCredentialPolicy struct {
	SecretIDTTL    time.Duration
	SecretIDUses   int
	RotationEvery  time.Duration
	RotationGrace  time.Duration
	RotatesOnLogin bool
}

// DefaultLoginCredentialPolicy is the shipped rotation policy.
func DefaultLoginCredentialPolicy() LoginCredentialPolicy {
	return LoginCredentialPolicy{
		SecretIDTTL:   LoginSecretIDTTL,
		SecretIDUses:  LoginSecretIDUses,
		RotationEvery: LoginSecretRotationInterval,
		RotationGrace: LoginSecretRotationGrace,
	}
}

// Validate enforces a credential that survives a reboot and can be rotated: a
// non-zero lifetime, at least two uses (one to log in, one for the next boot),
// and a rotation interval shorter than the lifetime so rotation is not a race
// with expiry.
func (p LoginCredentialPolicy) Validate() error {
	if p.SecretIDTTL <= 0 {
		return Invalid("login_secret_id_ttl", "must be greater than zero so the credential survives a reboot")
	}
	if p.SecretIDUses < 2 {
		return Invalid("login_secret_id_uses", "must allow at least two logins so a reboot is not the last use")
	}
	if p.RotationEvery <= 0 {
		return Invalid("login_secret_id_rotation", "must be greater than zero")
	}
	if p.RotationEvery >= p.SecretIDTTL {
		return Invalid("login_secret_id_rotation", "must be shorter than the SecretID lifetime")
	}
	if p.RotationGrace < 0 || p.RotationGrace >= p.SecretIDTTL {
		return Invalid("login_secret_id_grace", "must be non-negative and shorter than the SecretID lifetime")
	}
	return nil
}

// RotateAt reports when a credential minted at mintedAt must be replaced, and
// until when the previous one keeps working.
func (p LoginCredentialPolicy) RotateAt(mintedAt time.Time) (rotateAt, previousExpiresAt time.Time) {
	return mintedAt.Add(p.RotationEvery), mintedAt.Add(p.RotationEvery + p.RotationGrace)
}

// SortBundles returns the approved bundle references sorted, so a policy and a
// test see a deterministic list.
func SortBundles(bundles []string) []string {
	out := append([]string(nil), bundles...)
	sort.Strings(out)
	return out
}

// IdentityError is a non-secret identity failure. It deliberately carries no
// credential, no SecretID, and no wrapping token: the role name and the host
// identity are safe to report.
type IdentityError struct {
	Operation string
	HostID    string
	Reason    string
}

func (e *IdentityError) Error() string {
	if e.HostID == "" {
		return fmt.Sprintf("openbao identity: %s: %s", e.Operation, e.Reason)
	}
	return fmt.Sprintf("openbao identity: %s for host %s: %s", e.Operation, e.HostID, e.Reason)
}

// RoleClaimError reports that a role name is already bound to another host. It
// is the refusal a second host gets when it tries to claim an existing role.
type RoleClaimError struct {
	RoleName    string
	ClaimedHost string
	RequestedBy string
}

func (e *RoleClaimError) Error() string {
	return fmt.Sprintf("openbao identity: role %s is already claimed by host %s; host %s cannot reuse it",
		e.RoleName, e.ClaimedHost, e.RequestedBy)
}

// WrapTokenConsumedError reports a second use of a one-use wrapping token. It is
// returned before any network call, so a replay cannot even reach OpenBao.
type WrapTokenConsumedError struct {
	HostID string
}

func (e *WrapTokenConsumedError) Error() string {
	if e.HostID == "" {
		return "openbao identity: wrapping token was already used; a wrapping token is one-use"
	}
	return fmt.Sprintf("openbao identity: wrapping token for host %s was already used; a wrapping token is one-use", e.HostID)
}
